import type { ReactNode } from 'react';

/**
 * Один показательный случай компонента в галерее кита: вариант, состояние или
 * характерная комбинация пропсов. Галерея собирает случаи автоматически, поэтому
 * каждый компонент несёт свои примеры рядом с собой и общих файлов никто не делит.
 */
export interface GalleryCase {
  /** Подпись под примером: вариант и состояние, как их называет дизайн. */
  title: string;
  node: ReactNode;
  /** Тёмный хром вместо светлой рабочей области — для атомов шелла. */
  dark?: boolean;
}

/**
 * Модуль `<Name>.gallery.tsx` обязан экспортировать `cases` и `title`
 * (имя компонента как в реестре дизайна).
 */
export interface GalleryModule {
  title: string;
  cases: GalleryCase[];
}
