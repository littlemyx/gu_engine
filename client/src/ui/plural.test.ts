import { describe, expect, it } from 'vitest';

import { plural, pluralize } from './plural';

describe('склонение по числу', () => {
  it('единственное — только у чисел на 1, кроме 11', () => {
    expect(plural(1, 'префаб', 'префаба', 'префабов')).toBe('префаб');
    expect(plural(21, 'префаб', 'префаба', 'префабов')).toBe('префаб');
    expect(plural(11, 'префаб', 'префаба', 'префабов')).toBe('префабов');
  });

  it('2–4 дают «префаба», кроме подростковых', () => {
    expect(plural(3, 'префаб', 'префаба', 'префабов')).toBe('префаба');
    expect(plural(24, 'префаб', 'префаба', 'префабов')).toBe('префаба');
    expect(plural(13, 'префаб', 'префаба', 'префабов')).toBe('префабов');
  });

  it('ноль и 5+ дают множественное', () => {
    expect(plural(0, 'префаб', 'префаба', 'префабов')).toBe('префабов');
    expect(plural(7, 'префаб', 'префаба', 'префабов')).toBe('префабов');
  });

  it('pluralize печатает число вместе со словом', () => {
    expect(pluralize(1, 'персонаж', 'персонажа', 'персонажей')).toBe('1 персонаж');
    expect(pluralize(5, 'персонаж', 'персонажа', 'персонажей')).toBe('5 персонажей');
  });
});
